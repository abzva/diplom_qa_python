"""Account response checks and cleanup of credentials owned by a test."""

import logging

import requests

from config import settings
from diplom_qa_python.api.session import ApiSession, read_json
from models.account import AccountResponse, Credentials, UserLookupResponse


logger = logging.getLogger(__name__)


def read_account_response(response: requests.Response) -> AccountResponse:
    logger.info("%s %s -> HTTP %s", response.request.method, response.url, response.status_code)
    assert response.status_code == 200, f"Unexpected HTTP status: {response.status_code}"
    result = AccountResponse.model_validate(read_json(response))
    logger.info("Account API body: responseCode=%s", result.responseCode)
    return result


def verify_login(session: ApiSession, credentials: Credentials) -> AccountResponse:
    return read_account_response(session.post(
        "/api/verifyLogin",
        data=credentials.model_dump(),
        timeout=settings.api_timeout,
    ))


def account_exists(session: ApiSession, email: str) -> bool:
    # API 14 looks up an email without a password; verifyLogin cannot do this.
    response = session.get(
        "/api/getUserDetailByEmail", params={"email": email}, timeout=settings.api_timeout,
    )
    assert response.status_code == 200, f"Unexpected HTTP status: {response.status_code}"
    result = UserLookupResponse.model_validate(read_json(response))
    if result.responseCode == 200:
        assert result.user is not None, "User lookup succeeded without user details"
        assert result.user.id > 0, "User lookup returned an invalid ID"
        assert result.user.email == email, "User lookup returned a different email"
        return True
    # Do not infer absence from authentication failure, an empty body or HTTP 404.
    # This negative response was checked on the real email lookup endpoint.
    assert (result.responseCode == 404
            and result.message == "Account not found with this email, try another email!"
            and result.user is None), (
        "User lookup did not explicitly confirm presence or absence"
    )
    return False


def cleanup_account(session: ApiSession, credentials: Credentials):
    """Only pass the original, unique credentials generated by account_data."""
    errors = []
    try:
        exists = account_exists(session, credentials.email)
    except Exception as error:
        errors.append(error)
        exists = True  # An unavailable lookup must not prevent our DELETE attempt.

    if exists:
        try:
            deleted = read_account_response(session.delete(
                "/api/deleteAccount", data=credentials.model_dump(), timeout=settings.api_timeout,
            ))
            assert deleted.responseCode == 200, "DELETE did not confirm success"
            assert deleted.message == "Account deleted!", "Unexpected DELETE message"
        except Exception as error:
            errors.append(error)
        try:
            assert not account_exists(session, credentials.email), "Account still exists after DELETE"
        except Exception as error:
            errors.append(error)

    if errors:
        raise ExceptionGroup("очистка не подтверждена", errors)
    logger.info("Cleanup confirmed by independent email lookup")
